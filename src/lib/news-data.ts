// Function to generate dynamic daily dates for all 50 articles so they always feel fresh every day
export function getFormattedDate(daysAgo: number): string {
  if (typeof window === "undefined" && typeof Date === "undefined") return "Today";
  const now = new Date();
  now.setDate(now.getDate() - daysAgo);
  const day = String(now.getDate()).padStart(2, "0");
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const year = now.getFullYear();

  if (daysAgo === 0) return `Hôm nay, ${day}/${month}/${year} (Vừa cập nhật)`;
  if (daysAgo === 1) return `Hôm qua, ${day}/${month}/${year}`;
  if (daysAgo <= 6) return `${daysAgo} ngày trước (${day}/${month})`;
  return `${day}/${month}/${year}`;
}

